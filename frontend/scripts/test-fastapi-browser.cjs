const { chromium, expect: baseExpect } = require("@playwright/test");
const expect = baseExpect.configure({ timeout: 60000 });
const assert = require("node:assert/strict");
const { randomUUID } = require("node:crypto");
const { execFileSync } = require("node:child_process");
const base = process.env.TEST_FRONTEND_URL || "http://127.0.0.1:3001";
const email = `frontend-${randomUUID()}@example.com`;
const password = `Test-${randomUUID()}`;
const pdf = execFileSync("python", ["-B", "-c", "import sys,pymupdf; d=pymupdf.open();p=d.new_page();p.insert_text((72,72),'Frontend Test\\nPython developer building APIs with SQL');sys.stdout.buffer.write(d.tobytes());d.close()"]);
async function main() {
  const browser = await chromium.launch({ channel: process.env.TEST_BROWSER_CHANNEL || "msedge", headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(120000);
  const errors = [], requests = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("response", async response => { if (response.url().includes(":8002/api/") && response.status() === 401) { const data = await response.json().catch(() => ({})); console.log("401 diagnostic:", new URL(response.url()).pathname, data.detail || "unauthorized"); } });
  page.on("request", request => { if (request.url().includes(":8002/api/")) requests.push({ path: new URL(request.url()).pathname, method: request.method(), headers: request.headers() }); });
  try {
    await page.goto(`${base}/signup`);
    await page.locator("#email").fill(email);
    await page.locator('input[name="password"]').fill(password);
    await page.getByRole("button", { name: "Create account", exact: true }).click();
    await page.waitForURL("**/login?**");
    await expect(page.getByText("Account created. Sign in to continue.")).toBeVisible();
    assert.equal(await page.evaluate(() => localStorage.getItem("ai_recruiter_token")), null);
    await page.locator('input[name="password"]').fill("wrong-password");
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(page.getByText("Incorrect email or password", { exact: true })).toBeVisible();
    assert.equal(await page.evaluate(() => localStorage.getItem("ai_recruiter_token")), null);
    await page.locator('input[name="password"]').fill(password);
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
    await page.waitForURL("**/onboarding");
    await expect(page.locator('input[type="file"]')).toBeEnabled();
    console.log("PASS signup/login contracts, rejected credentials, stored JWT, and new-user onboarding");

    await page.locator('input[type="file"]').setInputFiles({ name: "bad.pdf", mimeType: "application/pdf", buffer: Buffer.from("not a PDF") });
    await expect(page.getByText("The uploaded file is not a readable PDF.")).toBeVisible();
    await expect(page.getByText(/Successfully parsed/)).toHaveCount(0);
    const upload = page.waitForResponse(r => r.url().endsWith("/api/resume/upload") && r.status() === 200);
    await page.locator('input[type="file"]').setInputFiles({ name: "resume.pdf", mimeType: "application/pdf", buffer: pdf });
    await upload;
    await expect(page.getByRole("textbox", { name: "Full name", exact: true })).toHaveValue("Frontend Test");
    await page.getByRole("textbox", { name: "Full name", exact: true }).fill("Reviewed Candidate");
    await page.getByRole("button", { name: "Save Profile", exact: true }).click();
    await page.waitForURL("**/dashboard");
    await page.goto(`${base}/profile`);
    await expect(page.getByRole("textbox", { name: "Full name", exact: true })).toHaveValue("Reviewed Candidate");
    await page.reload();
    await expect(page.getByRole("textbox", { name: "Full name", exact: true })).toHaveValue("Reviewed Candidate");
    console.log("PASS real PDF upload, failure feedback, profile review/save, and persisted reload");

    await page.goto(`${base}/new-email`);
    await page.getByRole("textbox", { name: "Company", exact: true }).fill("Integration Labs");
    await page.getByRole("textbox", { name: "Role title", exact: true }).fill("Backend Engineer");
    await page.getByRole("textbox", { name: "Job description", exact: true }).fill("Build Python APIs with SQL and Docker.");
    await page.route("**/api/jobs/analyze", route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ detail: "Analysis temporarily unavailable" }) }));
    await page.getByRole("button", { name: "Analyze & Extract Needs" }).click();
    await expect(page.getByText("Analysis temporarily unavailable", { exact: true })).toBeVisible();
    await page.unroute("**/api/jobs/analyze");
    await page.getByRole("button", { name: "Analyze & Extract Needs" }).click();
    await page.getByRole("button", { name: "Proceed to Situation" }).click();
    await page.getByRole("button", { name: "Compute Matching Points" }).click();
    await expect(page.getByText("Matched skills", { exact: true })).toBeVisible();
    await expect(page.getByText("Docker", { exact: true })).toBeVisible();
    const generation = page.waitForResponse(r => r.url().endsWith("/api/email/generate") && r.request().method() === "POST");
    await page.getByRole("button", { name: "Generate Factual Recruiter Email" }).click();
    const response = await generation;
    assert.equal(response.status(), 200);
    const generated = await response.json();
    assert.equal(typeof generated.draft_id, "number");
    await expect(page.getByText("Review candidate availability before sending.")).toBeVisible();
    await page.getByRole("textbox", { name: "Subject line", exact: true }).fill("Reviewed outreach");
    await page.getByRole("button", { name: "Evidence Visible" }).click();
    await page.getByRole("textbox", { name: "Email body", exact: true }).fill("I build Python APIs with SQL and would welcome a conversation.");
    await page.getByRole("button", { name: "Save to Tracker", exact: true }).click();
    await page.waitForURL("**/tracker");
    await expect(page.getByText("Reviewed outreach", { exact: true })).toBeVisible();
    console.log("PASS job analysis error handling, real semantic matching, generated warnings, and saved-draft editing");

    const status = page.getByRole("combobox", { name: `Status for draft ${generated.draft_id}`, exact: true });
    const update = page.waitForResponse(r => r.url().endsWith(`/api/drafts/${generated.draft_id}`) && r.request().method() === "PUT");
    await status.selectOption("Interview");
    assert.equal((await update).status(), 200);
    await page.reload();
    await expect(page.getByRole("combobox", { name: `Status for draft ${generated.draft_id}`, exact: true })).toHaveValue("Interview");
    await page.getByRole("link", { name: "Open draft", exact: true }).click();
    await page.waitForURL(`**/drafts/${generated.draft_id}`);
    await expect(page.getByRole("textbox", { name: "Subject line", exact: true })).toHaveValue("Reviewed outreach");
    await expect(page.getByRole("combobox", { name: "Application status" })).toHaveValue("Interview");
    await page.getByRole("textbox", { name: "Subject line", exact: true }).fill("Edited in detail view");
    await page.getByRole("button", { name: "Save changes", exact: true }).click();
    await expect(page.getByText("Draft saved.", { exact: true })).toBeVisible();
    await page.reload();
    await expect(page.getByRole("textbox", { name: "Subject line", exact: true })).toHaveValue("Edited in detail view");
    await page.goto(`${base}/tracker`);
    const deletion = page.waitForResponse(r => r.url().endsWith(`/api/drafts/${generated.draft_id}`) && r.request().method() === "DELETE");
    await page.getByRole("button", { name: `Delete draft ${generated.draft_id}`, exact: true }).click();
    assert.equal((await deletion).status(), 204);
    await page.reload();
    await expect(page.getByText("No saved drafts yet. Generate an email to get started.")).toBeVisible();
    console.log("PASS tracker status persistence, draft detail edits, and deletion across reloads");

    const token = await page.evaluate(() => localStorage.getItem("ai_recruiter_token"));
    assert(token);
    const protectedRequests = requests.filter(r => r.path.startsWith("/api/profile") || r.path.startsWith("/api/resume") || r.path.startsWith("/api/jobs") || r.path.startsWith("/api/match") || r.path.startsWith("/api/email") || r.path.startsWith("/api/drafts"));
    assert(protectedRequests.length > 10);
    for (const request of protectedRequests) assert.match(request.headers.authorization || "", /^Bearer /);
    assert(requests.some(r => r.path === "/api/resume/upload" && r.headers["content-type"]?.startsWith("multipart/form-data; boundary=")));
    await page.evaluate(() => { localStorage.setItem("ai_recruiter_token", "expired-token"); window.dispatchEvent(new Event("auth-changed")); });
    await page.waitForURL("**/login");
    assert.equal(await page.evaluate(() => localStorage.getItem("ai_recruiter_token")), null);
    await page.locator("#email").fill(email);
    await page.locator('input[name="password"]').fill(password);
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
    await page.waitForURL("**/dashboard");
    await page.getByTitle("Logout").click();
    await page.waitForURL("**/login");
    assert.equal(await page.evaluate(() => localStorage.getItem("ai_recruiter_token")), null);
    assert.deepEqual(errors, []);
    console.log("PASS automatic Bearer headers, multipart uploads, expired-session recovery, logout, and no browser runtime errors");
    console.log("All FastAPI frontend browser checks passed.");
  } finally { await browser.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
